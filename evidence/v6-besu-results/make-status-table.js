// Generates STATUS-TABLE.md from REPORT.md's result table (the single source) — counts are computed, classes are derived by explicit rules.
const fs = require("fs");
const [report, out] = process.argv.slice(2);
const lines = fs.readFileSync(report, "utf8").split("\n");
const start = lines.findIndex((l) => l.startsWith("| ID | Title |"));
const rows = [];
for (let i = start + 2; i < lines.length && lines[i].startsWith("|"); i++) {
  const c = lines[i].split("|").slice(1, -1).map((x) => x.trim());
  rows.push({ id: c[0], title: c[1], network: c[2], path: c[3], result: c[4], evidence: c[5] || "" });
}
const status = (r) => { const m = r.result.replace(/\*/g, "").match(/^(PASS|FAIL|BLOCKED|INCONCLUSIVE|NOT-RUN|SUPERSEDED)/); return m ? m[1] : "UNCLASSIFIED"; };
function classes(r) {
  const out = [];
  const net = r.network, id = r.id;
  if (id.startsWith("E0")) { out.push("Synthetic benchmark"); out.push("TEST-ONLY-SEED"); return out; }
  if (id.startsWith("A14")) { out.push("Baseline"); return out; }
  if (net === "Net-Fork") out.push("Test-fork (compressed constants)");
  else if (net.includes("Net-Fork")) { out.push("Baseline"); out.push("Test-fork for 3 cases"); }
  else out.push("Baseline");
  if (/SIMULATION/.test(r.result) || /SIMULATION/.test(r.id) || /SIMULATION/.test(r.title)) out.push("Simulation (eth_call, nothing mined)");
  if (/Net-F1\b|Net-F3\b|Net-F6\b/.test(net.replace(/\(\+ control[^)]*\)/, "")) && !out.includes("Test-fork (compressed constants)")) out.push("TEST-ONLY-SEED (rate history)");
  return out;
}
const counts = {};
for (const r of rows) { r.status = status(r); counts[r.status] = (counts[r.status] || 0) + 1; r.cls = classes(r).join(" + "); }
const esc = (s) => s.replace(/\|/g, "\\|").replace(/\*\*/g, "");
const short = (s, n) => { const t = esc(s); return t.length > n ? t.slice(0, n - 1) + "…" : t; };
let md = "# Status table (generated from REPORT.md)\n\n";
md += "Generated by `evidence/v6-besu-results/make-status-table.js` from the result table in `testing-evidence/besu-live-test-v4-2026-10-03/REPORT.md` (the single source).\n";
md += `Counts are computed, not typed: **${rows.length} rows — ` + Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(", ") + "**.\n\n";
md += "Evidence class is derived by these rules (a row can carry more than one label): Network exactly `Net-Fork` → test-fork; a row mixing `Net-Fork` with other networks → baseline + test-fork for the listed cases; IDs E01–E05 → synthetic benchmark (TEST-ONLY-SEED); result/ID/title containing `SIMULATION` → simulation; Network containing Net-F1, Net-F3 or Net-F6 (seeded rate history) → TEST-ONLY-SEED; everything else → baseline. The class is a reading aid; the row text in REPORT.md is authoritative.\n\n";
md += "| # | ID | Network | Path | Status | Evidence class | Result cell as written in REPORT.md (first 90 characters) |\n|---|---|---|---|---|---|---|\n";
rows.forEach((r, i) => { md += `| ${i + 1} | ${short(r.id, 70)} | ${short(r.network, 40)} | ${short(r.path, 14)} | **${r.status}** | ${r.cls} | ${short(r.result, 90)} |\n`; });
md += "\n## NOT-RUN (open, not executed)\n" + rows.filter((r) => r.status === "NOT-RUN").map((r) => `- ${esc(r.id)}`).join("\n") + "\n";
md += "\n## SUPERSEDED (kept for history, not counted as PASS)\n" + rows.filter((r) => r.status === "SUPERSEDED").map((r) => `- ${esc(r.id)}`).join("\n") + "\n";
fs.writeFileSync(out, md);
console.log(JSON.stringify(counts), "rows", rows.length);
